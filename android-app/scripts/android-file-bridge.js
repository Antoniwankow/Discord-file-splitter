(function () {
  'use strict';
  const Capacitor = window.Capacitor;
  if (!Capacitor || typeof Capacitor.isNativePlatform !== 'function' || !Capacitor.isNativePlatform()) return;
  const FilePicker = typeof Capacitor.registerPlugin === 'function' ? Capacitor.registerPlugin('FilePicker') : Capacitor.Plugins && Capacitor.Plugins.FilePicker;
  const SystemFileSaver = typeof Capacitor.registerPlugin === 'function' ? Capacitor.registerPlugin('SystemFileSaver') : Capacitor.Plugins && Capacitor.Plugins.SystemFileSaver;
  if (!FilePicker || !SystemFileSaver) return;

  let outputDirectory = localStorage.getItem('android-output-directory') || '';
  let pickerBusy = false;
  let nativeSaveQueue = Promise.resolve();
  const folderCache = new Map();
  const CHUNK_SIZE = 4 * 1024 * 1024;
  const PARTS_ROOT_NAME = 'Parts';
  const MERGED_ROOT_NAME = 'Merged files';

  function cleanUri(uri) { return String(uri || '').trim().replace(/\s+/g, ''); }
  function safeFolderName(name) {
    return String(name || 'File').replace(/[\\/:*?"<>|]/g, '_').replace(/[. ]+$/g, '').slice(0, 120) || 'File';
  }

  // Real part names generated by the web app:
  // original.ext_part001of005.part
  const PART_FILE_RE = /^(.*)_part(\d+)(?:of\d+)?\.part$/i;
  function parsePartFileName(fileName) {
    const match = String(fileName || '').match(PART_FILE_RE);
    if (!match) return null;
    return { originalName: match[1], partNumber: Number(match[2]) };
  }
  function isPartFile(fileName) { return !!parsePartFileName(fileName) || /\.part$/i.test(String(fileName || '')); }
  function originalNameFromPart(fileName) {
    const parsed = parsePartFileName(fileName);
    return parsed ? parsed.originalName : String(fileName || 'part').replace(/\.part$/i, '');
  }

  function mimeTypeFromName(fileName) {
    const name = String(fileName || '').toLowerCase();
    const ext = name.includes('.') ? name.slice(name.lastIndexOf('.') + 1) : '';
    const map = {
      txt: 'text/plain', csv: 'text/csv', json: 'application/json', xml: 'application/xml', html: 'text/html', htm: 'text/html', css: 'text/css', js: 'text/javascript',
      pdf: 'application/pdf', zip: 'application/zip', rar: 'application/vnd.rar', '7z': 'application/x-7z-compressed',
      doc: 'application/msword', docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', xls: 'application/vnd.ms-excel', xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      ppt: 'application/vnd.ms-powerpoint', pptx: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
      jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png', gif: 'image/gif', webp: 'image/webp',
      mp3: 'audio/mpeg', wav: 'audio/wav', ogg: 'audio/ogg', m4a: 'audio/mp4', mp4: 'video/mp4', webm: 'video/webm', mkv: 'video/x-matroska', mov: 'video/quicktime', avi: 'video/x-msvideo'
    };
    return map[ext] || 'application/octet-stream';
  }

  async function getOrCreateFolder(parentUri, name) {
    const key = `${cleanUri(parentUri)}::${name}`;
    if (folderCache.has(key)) return folderCache.get(key);
    const result = await SystemFileSaver.createDirectory({ parentUri: cleanUri(parentUri), name });
    const uri = result && result.uri;
    if (!uri) throw new Error(`Android did not return the URI of folder "${name}".`);
    folderCache.set(key, uri);
    return uri;
  }

  async function ensureOutputFolders(root) {
    const cleanRoot = cleanUri(root);
    if (!cleanRoot) return null;
    const partsRoot = await getOrCreateFolder(cleanRoot, PARTS_ROOT_NAME);
    const mergedRoot = await getOrCreateFolder(cleanRoot, MERGED_ROOT_NAME);
    return { partsRoot, mergedRoot };
  }

  async function chooseOutputDirectory() {
    if (pickerBusy) return outputDirectory;
    pickerBusy = true;
    try {
      const result = await FilePicker.pickDirectory();
      if (!result || !result.path) return outputDirectory;
      const selected = cleanUri(result.path);
      if (!selected.startsWith('content://')) throw new Error('Android returned an invalid directory URI.');
      try { await SystemFileSaver.persistDirectory({ uri: selected }); } catch (e) { console.warn('Could not persist directory permission:', e); }
      folderCache.clear();
      await ensureOutputFolders(selected);
      outputDirectory = selected;
      localStorage.setItem('android-output-directory', outputDirectory);
      const button = document.getElementById('androidOutputDirectoryButton');
      if (button) button.textContent = '📁 Output folder selected';
      return outputDirectory;
    } catch (e) {
      if (!String(e && e.message || e).toLowerCase().includes('canceled')) alert(`Could not select output folder: ${e.message || e}`);
      return '';
    } finally { pickerBusy = false; }
  }

  async function ensureOutputDirectory() {
    if (outputDirectory && outputDirectory.startsWith('content://')) {
      try { await ensureOutputFolders(outputDirectory); return outputDirectory; } catch (e) { console.warn('Stored output directory is no longer usable:', e); }
    }
    outputDirectory = '';
    localStorage.removeItem('android-output-directory');
    return chooseOutputDirectory();
  }

  async function nativePickFiles(input, multiple, targetId) {
    try {
      const result = await FilePicker.pickFiles({ limit: multiple ? 0 : 1 });
      if (!result || !result.files || result.files.length === 0) return false;
      const files = [];
      for (const picked of result.files) {
        if (!picked.path) continue;
        const response = await fetch(Capacitor.convertFileSrc(picked.path));
        if (!response.ok) throw new Error(`Could not read file ${picked.name || ''}`);
        const blob = await response.blob();
        files.push(new File([blob], picked.name || 'file', { type: picked.mimeType || blob.type || 'application/octet-stream', lastModified: picked.modifiedAt || Date.now() }));
      }
      if (!files.length) return false;
      const dt = new DataTransfer();
      for (const file of files) dt.items.add(file);
      input.files = dt.files;
      if (input.id === 'mergeInput') {
        const firstPart = files.find(file => isPartFile(file.name));
        window.__androidOriginalMergedFileName = firstPart ? originalNameFromPart(firstPart.name) : '';
      }
      if (typeof window.updateFileName === 'function') window.updateFileName(input, targetId);
      if (input.id === 'splitInput' && typeof window.updatePreview === 'function') window.updatePreview();
      if (input.id === 'mergeInput' && typeof window.checkPartsList === 'function') window.checkPartsList();
      return true;
    } catch (e) {
      if (!String(e && e.message || e).toLowerCase().includes('canceled')) alert('Could not select file.');
      return false;
    }
  }

  function base64FromBlob(blob) {
    return new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onerror = () => reject(reader.error || new Error('Could not read file data'));
      reader.onload = () => { const value = String(reader.result || ''); const comma = value.indexOf(','); resolve(comma >= 0 ? value.slice(comma + 1) : value); };
      reader.readAsDataURL(blob);
    });
  }

  async function saveBlobNative(blob, fileName) {
    let name = String(fileName || 'download.bin');
    if (!isPartFile(name) && window.__androidOriginalMergedFileName) name = window.__androidOriginalMergedFileName;

    const root = await ensureOutputDirectory();
    if (!root) return false;

    const part = isPartFile(name);
    const parsed = parsePartFileName(name);
    const folder1 = part ? PARTS_ROOT_NAME : MERGED_ROOT_NAME;
    const folder2 = part ? safeFolderName(parsed ? parsed.originalName : originalNameFromPart(name)) : '';

    // Pass the selected root to native code and let Android resolve the complete
    // destination path in one operation. This avoids relying on chained document
    // URIs in JavaScript, which some Android DocumentsProviders mishandle.
    const started = await SystemFileSaver.startFile({
      rootUri: cleanUri(root),
      folder1,
      folder2,
      name,
      mimeType: mimeTypeFromName(name)
    });
    const uri = started && started.uri;
    if (!uri) throw new Error('Android did not return the file URI.');

    try {
      for (let offset = 0; offset < blob.size; offset += CHUNK_SIZE) {
        const chunk = blob.slice(offset, Math.min(offset + CHUNK_SIZE, blob.size));
        await SystemFileSaver.writeChunk({ uri: cleanUri(uri), data: await base64FromBlob(chunk) });
      }
      await SystemFileSaver.finishFile({ uri: cleanUri(uri) });
      return true;
    } catch (e) {
      try { await SystemFileSaver.finishFile({ uri: cleanUri(uri) }); } catch (_) {}
      throw e;
    }
  }

  document.addEventListener('click', (event) => {
    const link = event.target && event.target.closest ? event.target.closest('a[download]') : null;
    if (!link) return;
    event.preventDefault(); event.stopImmediatePropagation();
    if (link.dataset.androidSaving === '1') return;
    link.dataset.androidSaving = '1';
    nativeSaveQueue = nativeSaveQueue.then(async () => {
      try {
        const response = await fetch(link.href);
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        const blob = await response.blob();
        if (await saveBlobNative(blob, link.getAttribute('download') || 'download.bin')) {
          link.textContent = '✅ Saved';
          link.classList.add('downloaded');
        }
      } catch (e) {
        console.error('Native save failed:', e);
        alert(`Could not save file: ${e.message || e}`);
      } finally { delete link.dataset.androidSaving; }
    });
  }, true);

  function installFilePickers() {
    const splitLabel = document.getElementById('splitLabel'), splitInput = document.getElementById('splitInput');
    const mergeLabel = document.getElementById('mergeLabel'), mergeInput = document.getElementById('mergeInput');
    if (splitLabel && splitInput) splitLabel.addEventListener('click', async (e) => { e.preventDefault(); e.stopImmediatePropagation(); await nativePickFiles(splitInput, false, 'splitInputText'); }, true);
    if (mergeLabel && mergeInput) mergeLabel.addEventListener('click', async (e) => { e.preventDefault(); e.stopImmediatePropagation(); await nativePickFiles(mergeInput, true, 'mergeInputText'); }, true);
  }

  function installOutputDirectoryButton() {
    const title = document.querySelector('h1');
    if (!title || document.getElementById('androidOutputDirectoryButton')) return;
    const button = document.createElement('button');
    button.id = 'androidOutputDirectoryButton'; button.type = 'button';
    button.textContent = outputDirectory ? '📁 Output folder selected' : '📁 Choose output folder';
    button.style.cssText = 'display:block;width:100%;margin:10px 0 20px;padding:12px 16px;box-sizing:border-box;';
    button.addEventListener('click', chooseOutputDirectory);
    title.insertAdjacentElement('afterend', button);
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => { installFilePickers(); installOutputDirectoryButton(); });
  else { installFilePickers(); installOutputDirectoryButton(); }
})();
